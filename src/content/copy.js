export const DEFAULT_LOCALE = 'en';
const LOCALE_STORAGE_KEY = 'portfolio-locale';

export const SUPPORTED_LOCALES = Object.keys(copy);

const normalizeLocale = (locale) =>
  typeof locale === 'string' ? locale.trim().toLowerCase() : '';

export const resolveLocale = (locale) => {
  const normalized = normalizeLocale(locale);
  if (!normalized) return DEFAULT_LOCALE;

  if (SUPPORTED_LOCALES.includes(normalized)) {
    return normalized;
  }

  const baseLocale = normalized.split('-')[0];
  if (SUPPORTED_LOCALES.includes(baseLocale)) {
    return baseLocale;
  }

  return DEFAULT_LOCALE;
};

export const detectBrowserLocale = () => {
  if (typeof navigator === 'undefined') return DEFAULT_LOCALE;

  const candidates = [navigator.language, ...(navigator.languages || [])];
  for (const candidate of candidates) {
    const resolved = resolveLocale(candidate);
    if (resolved !== DEFAULT_LOCALE || normalizeLocale(candidate).startsWith(DEFAULT_LOCALE)) {
      return resolved;
    }
  }

  return DEFAULT_LOCALE;
};

export const getPreferredLocale = () => {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  return saved ? resolveLocale(saved) : detectBrowserLocale();
};

export const setPreferredLocale = (locale) => {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(LOCALE_STORAGE_KEY, resolveLocale(locale));
};

export const getCopy = (locale) => {
  const resolved = locale ? resolveLocale(locale) : getPreferredLocale();
  return copy[resolved] || copy[DEFAULT_LOCALE];
};

export default copy;
